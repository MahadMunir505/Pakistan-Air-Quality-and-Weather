"""Flask application: serves the REST API and the static HTML/CSS/JS frontend.

Run from the project root:  python backend/app.py
"""
import sys
from pathlib import Path

from flask import Flask, send_from_directory

sys.path.append(str(Path(__file__).resolve().parents[1]))
import config  # noqa: E402

if not config.DB_PATH.exists() or not config.ETL_REPORT_PATH.exists():
    sys.exit("Processed data not found. Run `python etl/etl_pipeline.py` first.")

from backend.api.routes import api  # noqa: E402

app = Flask(__name__, static_folder=str(config.FRONTEND_DIR), static_url_path="")
app.register_blueprint(api)


@app.get("/")
def index():
    return send_from_directory(config.FRONTEND_DIR, "index.html")


@app.get("/report")
def eda_report():
    """Static EDA report generated by eda/exploratory_analysis.py."""
    if not config.EDA_REPORT_PATH.exists():
        return "EDA report not generated yet. Run: python eda/exploratory_analysis.py", 404
    return send_from_directory(config.EDA_REPORT_PATH.parent, config.EDA_REPORT_PATH.name)


if __name__ == "__main__":
    app.run(host="127.0.0.1", port=5000, debug=False)
